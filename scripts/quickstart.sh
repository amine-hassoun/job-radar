#!/usr/bin/env bash
# From "I have an AWS account" to a working job-radar in one command:
#
#   ./scripts/quickstart.sh you@example.com        # add --yes to skip the confirmation prompt
#
# It deploys the stack to the account/region your AWS CLI points at, creates the shared secret,
# writes extension/config.js, loads the first RemoteOK jobs, and waits for you to confirm the
# email subscription so it can send you the first digest. Safe to re-run.
set -euo pipefail
export AWS_PAGER=""
cd "$(dirname "$0")/.."

EMAIL=""; YES=0
for arg in "$@"; do
  case "$arg" in
    -y|--yes) YES=1 ;;
    *@*.*) EMAIL="$arg" ;;
    *) echo "Usage: $0 you@example.com [--yes]"; exit 2 ;;
  esac
done
[ -n "$EMAIL" ] || { echo "Usage: $0 you@example.com [--yes]   (the address that receives the daily digest)"; exit 2; }

say()  { printf '\n==> %s\n' "$*"; }
fail() { echo "ERROR: $*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || fail "'$1' is not installed. $2"; }

need aws       "Install the AWS CLI v2: https://docs.aws.amazon.com/cli/latest/userguide/getting-started-install.html"
need terraform "Install Terraform 1.6 or newer: https://developer.hashicorp.com/terraform/install"
need openssl   "It is preinstalled on macOS, Linux and WSL."

# No `| head -1` here: under pipefail, head closing the pipe early can make the writer die with SIGPIPE.
TF_OUT=$(terraform version)
TF_VERSION=$(sed -E 's/[^0-9]*([0-9]+\.[0-9]+).*/\1/' <<<"${TF_OUT%%$'\n'*}")
TF_MAJOR=${TF_VERSION%%.*}; TF_MINOR=${TF_VERSION#*.}   # plain arithmetic: no reliance on `sort -V` (missing on older macOS)
if [ "$TF_MAJOR" -lt 1 ] || { [ "$TF_MAJOR" -eq 1 ] && [ "$TF_MINOR" -lt 6 ]; }; then
  fail "Terraform $TF_VERSION is too old: this project needs 1.6 or newer."
fi

say "Checking your AWS account"
ACCOUNT=$(aws sts get-caller-identity --query Account --output text 2>/dev/null) \
  || fail "The AWS CLI has no working credentials. Run 'aws configure' (or set AWS_PROFILE), then run this again."
REGION="${AWS_REGION:-${AWS_DEFAULT_REGION:-$(aws configure get region 2>/dev/null || true)}}"
[ -n "$REGION" ] || fail "No AWS region is set. Run: export AWS_REGION=eu-west-3   (any region works)"
echo "Account $ACCOUNT, region $REGION"

cat <<MSG

This will create, in account $ACCOUNT ($REGION): 3 Lambda functions, 1 DynamoDB table (provisioned,
4 read / 6 write units), 2 EventBridge schedules, 1 SNS topic, 3 CloudWatch alarms and their IAM roles.
Nothing here bills by the hour, so the expected cost is \$0/month. Terraform state stays local in infra/
(see the README to move it to S3 later).
MSG
if [ "$YES" -ne 1 ]; then
  read -r -p "Continue? [y/N] " answer
  [[ "$answer" =~ ^[Yy]$ ]] || { echo "Aborted, nothing was created."; exit 1; }
fi

SECRET_NAME=/job-radar/ingest-shared-secret
say "Creating the shared secret (kept in SSM Parameter Store, never in Terraform state)"
if aws ssm get-parameter --region "$REGION" --name "$SECRET_NAME" >/dev/null 2>&1; then
  echo "Already exists: keeping it."
else
  aws ssm put-parameter --region "$REGION" --name "$SECRET_NAME" --type SecureString \
    --value "$(openssl rand -hex 32)" >/dev/null
  echo "Created."
fi

if [ -f infra/backend.tf ] && grep -q "amine-hassoun-aws-terraform-infra-state" infra/backend.tf; then
  mv infra/backend.tf infra/backend.tf.disabled
  echo "infra/backend.tf points at the author's state bucket: moved aside, using local state instead."
fi
cat > infra/terraform.tfvars <<TFVARS
notification_email = "$EMAIL"
aws_region         = "$REGION"
TFVARS

say "Deploying with Terraform (about 2 minutes)"
terraform -chdir=infra init -input=false
terraform -chdir=infra apply -auto-approve -input=false

URL=$(terraform -chdir=infra output -raw ingest_url)
TOPIC=$(terraform -chdir=infra output -raw sns_topic_arn)
KEY=$(aws ssm get-parameter --region "$REGION" --name "$SECRET_NAME" --with-decryption \
      --query Parameter.Value --output text)

say "Configuring the extension"
cat > extension/config.js <<CONFIG
// Generated by scripts/quickstart.sh. Gitignored: never commit this file.
const JOB_RADAR_CONFIG = {
  endpoint: "$URL",
  key: "$KEY",
};
CONFIG
echo "Wrote extension/config.js"
if ! grep -q "lambda-url.$REGION.on.aws" extension/manifest.json; then
  sed -i.bak -E "s#lambda-url\.[a-z0-9-]+\.on\.aws#lambda-url.$REGION.on.aws#" extension/manifest.json
  rm -f extension/manifest.json.bak
  echo "Updated extension/manifest.json for region $REGION."
fi

say "Fetching the first jobs from RemoteOK (up to 2 minutes)"
OUT=$(mktemp)
aws lambda invoke --region "$REGION" --function-name job-radar-fetch --cli-read-timeout 130 "$OUT" >/dev/null
cat "$OUT"; echo

say "Confirm your email"
echo "AWS sent a confirmation link to $EMAIL (check spam). Click it: I'll wait up to 5 minutes."
POLL="${QS_POLL_SECONDS:-5}"; CONFIRMED=0
for _ in $(seq 1 $(( ${QS_WAIT_SECONDS:-300} / POLL ))); do
  SUB=$(aws sns list-subscriptions-by-topic --region "$REGION" --topic-arn "$TOPIC" \
        --query 'Subscriptions[0].SubscriptionArn' --output text 2>/dev/null || true)
  if [[ "$SUB" == arn:aws:sns:* ]]; then CONFIRMED=1; break; fi
  sleep "$POLL"
done
if [ "$CONFIRMED" -eq 1 ]; then
  echo "Confirmed. Sending your first digest..."
  aws lambda invoke --region "$REGION" --function-name job-radar-digest "$OUT" >/dev/null
  cat "$OUT"; echo
else
  echo "Not confirmed yet. Once you have clicked the link, send the first digest with:"
  echo "  aws lambda invoke --region $REGION --function-name job-radar-digest /dev/stdout"
fi
rm -f "$OUT"

EXT_PATH="$(pwd)/extension"
if command -v wslpath >/dev/null 2>&1; then EXT_PATH="$(wslpath -w "$EXT_PATH")"; fi
cat <<DONE

Done. Last step (30 seconds):
  1. Open chrome://extensions, turn on "Developer mode", click "Load unpacked" and choose:
       $EXT_PATH
  2. Open any LinkedIn job: a Capture button appears next to Save.
     Click the extension icon to see your RemoteOK matches.

Daily digest: 05:30 UTC.  Check everything: ./scripts/verify.sh.  Remove everything: see "Tear it all down" in the README.
DONE
